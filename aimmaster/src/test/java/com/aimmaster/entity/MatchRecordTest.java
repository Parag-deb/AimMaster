package com.aimmaster.entity;

import org.junit.jupiter.api.Test;

import java.time.Instant;

import static org.junit.jupiter.api.Assertions.*;

class MatchRecordTest {

    @Test
    void matchRecordCreatedWithAllFields() {
        Instant now = Instant.now();
        MatchRecord record = new MatchRecord(
                1,  // playerId
                5,  // roomId
                100, // score
                0.75, // accuracy
                20, // shotsFired
                15, // hits
                now
        );

        assertEquals(1, record.getPlayerId());
        assertEquals(5, record.getRoomId());
        assertEquals(100, record.getScore());
        assertEquals(0.75, record.getAccuracy());
        assertEquals(20, record.getShotsFired());
        assertEquals(15, record.getHits());
        assertEquals(now, record.getTimestamp());
        assertNull(record.getId()); // ID is generated by DB
    }

    @Test
    void matchRecordNoArgsConstructorExists() {
        // JPA requires no-arg constructor
        MatchRecord record = new MatchRecord();
        assertNotNull(record);
    }
}